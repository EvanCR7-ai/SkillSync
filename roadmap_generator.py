"""
SkillSync | CareerPath AI - Roadmap Generator
Processes, formats, enriches, and structures 8-week personalized roadmaps.
"""

from typing import List, Dict, Any


def format_roadmap_for_display(roadmap_weeks: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Validates and formats the 8-week roadmap items, ensuring all necessary UI keys exist.
    """
    formatted = []
    for idx, week in enumerate(roadmap_weeks, start=1):
        week_num = week.get("week_number", idx)
        topic = week.get("topic", f"Week {week_num}: Advanced Core Mastery")
        
        # Normalize focus skills
        skills = week.get("focus_skills", week.get("skills", []))
        if isinstance(skills, str):
            skills = [s.strip() for s in skills.split(",") if s.strip()]

        # Normalize objectives
        objectives = week.get("detailed_objectives", week.get("objectives", []))
        if isinstance(objectives, str):
            objectives = [objectives]

        # Normalize resources
        resources = week.get("recommended_resources", week.get("resources", []))
        if isinstance(resources, str):
            resources = [resources]

        # Normalize exercises
        exercises = week.get("practical_exercises", week.get("exercises", []))
        if isinstance(exercises, str):
            exercises = [exercises]

        outcome = week.get("expected_outcome", week.get("outcome", "Verified practical implementation."))
        hours = week.get("estimated_hours", "8–10 hours")

        is_capstone = (week_num == 8 or "capstone" in topic.lower())

        formatted.append({
            "week_number": week_num,
            "topic": topic,
            "focus_skills": skills,
            "objectives": objectives,
            "resources": resources,
            "exercises": exercises,
            "expected_outcome": outcome,
            "estimated_hours": hours,
            "is_capstone": is_capstone
        })
    return formatted


def calculate_roadmap_metrics(roadmap_weeks: List[Dict[str, Any]], weekly_hours_str: str) -> Dict[str, Any]:
    """
    Calculates cumulative metrics for the 8-week roadmap.
    """
    total_weeks = len(roadmap_weeks)
    
    # Parse approximate hours from string like '10–15', '5–10', '15–20', '20+'
    avg_hours_map = {
        "3–5": 4,
        "5–10": 7.5,
        "10–15": 12.5,
        "15–20": 17.5,
        "20+": 25,
        "3-5": 4,
        "5-10": 7.5,
        "10-15": 12.5,
        "15-20": 17.5,
    }
    avg_weekly = avg_hours_map.get(weekly_hours_str.replace(" hours/week", "").strip(), 10.0)
    total_estimated_hours = int(avg_weekly * total_weeks)

    total_exercises = sum(len(w.get("exercises", [])) for w in roadmap_weeks)
    total_skills_targeted = len(set(
        skill
        for w in roadmap_weeks
        for skill in w.get("focus_skills", [])
    ))

    return {
        "total_weeks": total_weeks,
        "avg_weekly_hours": avg_weekly,
        "total_estimated_hours": total_estimated_hours,
        "total_exercises": total_exercises,
        "total_skills_targeted": total_skills_targeted,
        "milestones": [
            {"week": 2, "label": "Foundational Fluency & Core Tools"},
            {"week": 4, "label": "Midway Checkpoint: Architecture & APIs"},
            {"week": 6, "label": "Advanced Scalability & Systems Design"},
            {"week": 8, "label": "Capstone Delivery & Job-Ready Portfolio Launch"}
        ]
    }


def generate_roadmap_markdown_summary(roadmap_weeks: List[Dict[str, Any]], target_role: str) -> str:
    """
    Generates a structured Markdown export of the 8-week roadmap.
    """
    lines = [
        f"# 8-Week Personalized Learning Roadmap: {target_role}",
        "Generated by SkillSync | CareerPath AI\n",
        "---",
        ""
    ]

    for w in roadmap_weeks:
        capstone_tag = " [🏆 CAPSTONE WEEK]" if w.get("is_capstone") else ""
        lines.append(f"## Week {w['week_number']}: {w['topic']}{capstone_tag}")
        lines.append(f"**Estimated Commitment:** {w['estimated_hours']}")
        
        if w.get("focus_skills"):
            lines.append(f"**Focus Skills:** {', '.join(w['focus_skills'])}")
        
        lines.append("\n### 🎯 Detailed Objectives:")
        for obj in w.get("objectives", []):
            lines.append(f"- {obj}")

        lines.append("\n### 📚 Recommended Resources:")
        for res in w.get("resources", []):
            lines.append(f"- {res}")

        lines.append("\n### 🛠️ Practical Exercises:")
        for ex in w.get("exercises", []):
            lines.append(f"- {ex}")

        lines.append(f"\n**🏁 Expected Outcome:** {w.get('expected_outcome', 'Complete and verified code.')}\n")
        lines.append("---\n")

    return "\n".join(lines)
